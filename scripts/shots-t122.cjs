// T-122 : captures 390 × 844 des nouveaux écrans (compte et enfants accueillis), clair et sombre.
// Usage : comme scripts/e2e.cjs (faux service en ligne et serveur de fichiers), puis node scripts/shots-t122.cjs [dossier]
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const A = require('./e2e-assistant.cjs');
const base = process.env.BASE || 'http://localhost:4173/pilote-am/';
const out = process.argv[2] || path.join(__dirname, 'out', 't122');

async function run(scheme) {
  const dir = path.join(out, scheme === 'dark' ? 'sombre' : 'clair');
  fs.mkdirSync(dir, { recursive: true });
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, colorScheme: scheme, locale: 'fr-FR', timezoneId: 'Europe/Paris', hasTouch: true, isMobile: true });
  // T-122 : le thème suit le parcours (l'app est en version jour par défaut ; « sombre » = version nuit choisie).
  if (scheme === 'dark') await ctx.addInitScript(() => { try { localStorage.setItem('pam-theme', 'dark'); } catch { /* rien */ } });
  await ctx.clock.install({ time: new Date('2026-11-26T10:00:00+01:00') });
  await ctx.clock.resume();
  const p = await ctx.newPage();
  const shot = async (n, full = false) => { await p.waitForTimeout(250); await p.screenshot({ path: path.join(dir, `${n}.png`), fullPage: full }); };
  await p.goto(base);
  await p.getByRole('button', { name: 'Créer mon compte gratuit' }).first().click();
  await p.getByLabel('Adresse e-mail').fill(`captures-${scheme}-${Date.now()}@exemple.fr`);
  await p.getByLabel('Mot de passe', { exact: true }).fill('Motdepasse-solide1');
  await p.getByRole('button', { name: 'Créer mon compte', exact: true }).click();
  await p.getByRole('heading', { name: 'Toi' }).waitFor();
  // Message de la mesure d'usage : fermé pour les captures.
  await p.getByLabel('Ton prénom').fill('Sonia');
  await p.getByLabel('Département où tu accueilles').fill('31 – Haute-Garonne');
  await shot('02-toi');
  await p.getByRole('button', { name: 'Ajouter un enfant accueilli' }).click();
  await A.continuer(p);
  await shot('04-etape1-erreurs');
  await p.getByLabel('Prénom de l’enfant').fill('Lou');
  await p.getByLabel('Nom de famille de l’employeur').fill('Petit');
  await p.getByLabel('E-mail du parent employeur (facultatif)').fill('claire.martin.petit@exemple.fr');
  await p.getByLabel('Téléphone du parent employeur (facultatif)').fill('06 12 34 56 78');
  await A.continuer(p);
  await shot('05b-etape2-rien-coche');
  await p.goto(base + '#/');
  await shot('24-aujourdhui-reprise');
  await p.getByRole('button', { name: 'Supprimer' }).click();
  await shot('24b-suppression-confirmee');
  await p.getByRole('button', { name: 'Garder' }).click();
  await p.goto(base + '#/plus');
  await shot('22-plus-enfants');
  await p.locator('a.li', { hasText: 'Contrat en cours de saisie' }).click();
  await shot('03-liste-etapes');
  await p.getByRole('button', { name: /^Reprendre/ }).click();
  await p.getByLabel('Date de début du contrat').fill('2025-09-01');
  await p.getByRole('radio', { name: /^CDI/ }).click();
  await p.getByRole('radio', { name: /^Régulier/ }).click();
  await A.continuer(p);
  await shot('06-etape2-annee');
  await p.getByRole('radio', { name: /^Année complète/ }).click();
  await A.continuer(p);
  await p.getByRole('radio', { name: /^Identique chaque semaine/ }).click();
  await shot('07a-etape3-a-l-arrivee');
  for (const j of A.JOURS.slice(0, 5)) await p.getByRole('button', { name: j, exact: true }).click();
  await p.getByLabel('Lundi, arrivée', { exact: true }).fill('08:00');
  await p.getByLabel('Lundi, départ', { exact: true }).fill('17:30');
  await p.getByRole('button', { name: 'Copier lundi sur les jours cochés' }).click();
  await p.getByLabel('Vendredi, départ', { exact: true }).fill('12:00');
  await shot('07-etape3-planning', true);
  await A.continuer(p);
  await p.getByLabel('Taux horaire net').fill('3,00');
  await A.continuer(p);
  await shot('08-etape4-salaire-erreur', true);
  await p.getByLabel('Taux horaire net').fill('3,50');
  await p.getByRole('radio', { name: /^Celles de la convention/ }).click();
  await A.continuer(p);
  await shot('09b-etape5-frais-rien-coche', true);
  await p.getByRole('radio', { name: /^Par jour d’accueil/ }).click();
  await p.getByRole('radio', { name: /^Fournis par les parents/ }).click();
  await p.getByRole('radio', { name: /^Non prévues/ }).click();
  await A.continuer(p);
  await shot('10-etape6-avant-arvela', true);
  await p.getByLabel(/^Jours de congés déjà pris/).fill('0');
  await p.getByRole('radio', { name: /^Non$/ }).click();
  await A.continuer(p);
  await shot('10b-etape6-absences');
  await p.getByLabel(/malade, avec certificat, déjà retenus/).fill('0');
  await A.continuer(p);
  await shot('11-recapitulatif', true);
  await p.getByRole('button', { name: 'Créer le contrat de Lou' }).click();
  await p.getByRole('heading', { name: 'Contrat de Lou créé' }).waitFor();
  await p.waitForTimeout(5000);
  await shot('23-contrat-cree');
  await p.getByRole('link', { name: /^La fiche de Lou/ }).click();
  await shot('12-fiche-enfant', true);
  await p.getByRole('link', { name: /^Les parents et leur lien/ }).click();
  await shot('13-parents-lien', true);
  await p.getByRole('link', { name: 'Retour' }).click();
  await p.getByRole('link', { name: /^Absences et congés/ }).click();
  await shot('14-absences-conges', true);
  await p.getByRole('button', { name: 'Déclarer une absence de Lou' }).click();
  await p.getByLabel('Jour de l’absence').fill('2026-12-03');
  await shot('21a-absence-de-lou-jour');
  await p.locator('dialog').getByRole('button', { name: 'Continuer' }).click();
  await shot('21-absence-de-lou');
  await p.keyboard.press('Escape');
  await p.getByRole('link', { name: 'Retour' }).click();
  await p.getByRole('link', { name: /^Changer le contrat/ }).click();
  await p.getByLabel('Date d’effet').fill('2027-01-01');
  await p.getByRole('switch', { name: /^Le salaire/ }).check();
  await shot('19-avenant');
  await p.getByRole('button', { name: 'Continuer' }).click();
  await p.getByLabel('Taux horaire net').fill('3,70');
  await shot('27-avenant-salaire', true);
  await p.goto(base + '#/plus');
  await p.locator('a.li', { hasText: 'Lou' }).first().click();
  await p.getByRole('link', { name: /^Fin du contrat/ }).click();
  await shot('20-fin-pourquoi', true);
  await p.getByRole('radio', { name: /^Les parents retirent l’enfant\b/ }).first().click();
  await p.getByRole('button', { name: 'Continuer' }).click();
  await p.getByRole('radio', { name: /^En main propre/ }).click();
  await p.getByLabel('Date de remise en main propre').fill('2026-12-02');
  await p.getByRole('radio', { name: /^Oui, effectué ou en cours/ }).click();
  await shot('25-fin-la-lettre', true);
  await p.getByRole('button', { name: 'Continuer' }).click();
  await shot('26-fin-ce-qui-est-du', true);
  await p.goto(base + '#/reglages');
  await shot('reglages-toi');
  await b.close();
}

(async () => {
  try { await run('light'); await run('dark'); console.log('Captures : ' + out); } catch (e) { console.error(e.message); process.exit(1); }
})();
